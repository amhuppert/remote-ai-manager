export interface CoreConversationPromptDeps {
  sendUserMessage: ConversationCore["sendUserMessage"];
  /** The core's admission, the same rules every entry uses; null when work may start. */
  admission: ConversationCore["admission"];
  /** A conversation that has not run takes the backend its first input chose. */
  adoptBackend(
    identity: ConversationIdentity,
    backend: AgentBackendId,
  ): Promise<void>;
  clearPendingPromptText(
    projectPath: string,
    storeSessionName: string,
    conversationId: string,
    expectedText: string,
  ): Promise<boolean>;
  /** The conversation command service: persists the command message and runs the command to its outcome. */
  dispatchCommand(
    input: ConversationCommandDispatchInput,
  ): Promise<RunCommandOutcome>;
  /** A command the backend cannot run, refused before anything is recorded; null when admitted. */
  commandRefusal(
    prompt: string,
    backend: AgentBackendId,
  ): Promise<PromptRefusal | null>;
  /** A command's explicit model, admitted for the project and canonicalized before anything is recorded. */
  admitCommandModel(input: {
    projectPath: string;
    backend: AgentBackendId;
    selection: BackendModelSelection;
  }): Promise<
    | { ok: true; selection: BackendModelSelection }
    | { ok: false; refusal: PromptRefusal }
  >;
  log: Pick<Logger, "info" | "warn">;
}

export interface CoreConversationPrompt {
  projectPath: string;
  target: ConversationTarget;
  conversation: ConversationState;
  body: RunPromptRequest;
}

/** What a conversation prompt route asks of the core: whether it runs a conversation, and its prompts. */
export interface CoreConversationPrompts {
  owns(conversationId: string): boolean;
  prompt(input: CoreConversationPrompt): Promise<Response>;
  /**
   * Whether `/collab` may take the conversation over now (null when it may),
   * with a fresh conversation taking the backend its first input chose.
   */
  admitCollaboration(input: CoreConversationPrompt): Promise<Response | null>;
}

/** What a refused prompt answers, whichever transport carried it. */
export interface PromptRefusal {
  status: number;
  body: ApiError & { refusal?: unknown };
}

/** How a prompt's turn or command ended. */
export interface PromptSettlement {
  error: string | null;
  aborted: boolean;
}

/** A prompt's outcome: refused before anything ran, or accepted and settling. */
export type CorePromptOutcome =
  | { kind: "refused"; refusal: PromptRefusal }
  | { kind: "accepted"; settled: Promise<PromptSettlement> };

/** A message to a conversation the core runs, as the core takes it from any transport. */
export interface CorePromptMessage {
  text: string;
  images?: ImagePayload[];
  documentFeedback?: DocumentFeedbackPayload;
  notepadFeedback?: readonly NotepadFeedbackPayload[];
  modelSelection?: BackendModelSelection;
  /** The backend the message chose; a conversation that has not run adopts it. */
  backend?: AgentBackendId;
  /** Who wrote it; review feedback alone is generated by CC. */
  inputOrigin?: "user" | "generated";
  /** An unattended turn (a kickoff with no person to ask): autonomous instructions, no questions. */
  autonomous?: boolean;
}

export interface CorePromptSend {
  projectPath: string;
  target: ConversationTarget;
  conversation: ConversationState;
  message: CorePromptMessage;
  /** Where its events go while it runs: a request's stream, or a server-side caller's. */
  sink: TurnStream;
  /** The person's draft the message was sent from, cleared once it is accepted; none for a server-side caller. */
  draft?: string;
}

/** What `/collab` asks of a conversation the core runs before the collaboration takes it over. */
export interface CoreCollaborationRequest {
  projectPath: string;
  target: ConversationTarget;
  conversation: ConversationState;
  text: string;
  backend?: AgentBackendId;
}

function refused(refusal: PromptRefusal): CorePromptOutcome {
  return { kind: "refused", refusal };
}

/** A run's seat takes work only from its run: no message or claim of a person's. */
function managedRefusal(conversation: ConversationState): PromptRefusal | null {
  if (conversation.role === null) return null;
  return {
    status: 403,
    body: {
      error: "Managed workflow conversations are not user-interactive",
      code: "MANAGED_CONVERSATION",
    },
  };
}

/** The HTTP answer to a refused prompt. */
function asResponse(refusal: PromptRefusal): Response {
  return NextResponse.json(refusal.body, { status: refusal.status });
}

/**
 * `/collab` is a claim: the backend must run it, it is held as a command
 * would be, and a fresh conversation adopts its chosen backend.
 */
export async function coreCollaborationRefusal(
  deps: Pick<
    CoreConversationPromptDeps,
    "admission" | "adoptBackend" | "commandRefusal"
  >,
  input: CoreCollaborationRequest,
): Promise<PromptRefusal | null> {
  const { projectPath, target, conversation } = input;
  const backend = input.backend ?? conversation.agentBackend;
  const refusal =
    managedRefusal(conversation) ??
    (await deps.commandRefusal(input.text, backend)) ??
    (await coreCommandHold(deps, conversation, "claim"));
  if (refusal !== null) return refusal;
  if (backend === conversation.agentBackend) return null;
  if (backendLocked(conversation))
    return backendMismatch(conversation, backend);
  await deps.adoptBackend(
    {
      projectPath,
      storeSessionName: conversationTargetStoreSessionName(target),
      conversationId: conversation.id,
    },
    backend,
  );
  return null;
}

export async function admitCoreCollaboration(
  deps: Pick<
    CoreConversationPromptDeps,
    "admission" | "adoptBackend" | "commandRefusal"
  >,
  input: CoreConversationPrompt,
): Promise<Response | null> {
  const refusal = await coreCollaborationRefusal(deps, {
    projectPath: input.projectPath,
    target: input.target,
    conversation: input.conversation,
    text: input.body.prompt.trim(),
    ...(input.body.backend !== undefined
      ? { backend: input.body.backend }
      : {}),
  });
  return refusal === null ? null : asResponse(refusal);
}

function backendMismatch(
  conversation: ConversationState,
  backend: AgentBackendId,
): PromptRefusal {
  return {
    status: 409,
    body: {
      error: `Backend mismatch: conversation uses "${conversation.agentBackend}" but request specified "${backend}"`,
      code: "BACKEND_MISMATCH",
    },
  };
}

/**
 * A project conversation keeps its existing refusal. A session conversation's
 * `/collab` is a claim, admitted by `coreCollaborationRefusal` and started by
 * its caller, never a message.
 */
function collaborationRefusal(target: ConversationTarget): PromptRefusal {
  if (target.scope === "project") {
    const refusal = new ProjectCollaborationUnsupportedError();
    return {
      status: refusal.statusCode,
      body: { error: refusal.message, code: refusal.code },
    };
  }
  return {
    status: 400,
    body: {
      error: "Collaboration Mode starts through its claim, not as a message",
      code: "COLLABORATION_CLAIM_REQUIRED",
    },
  };
}

const REFUSAL_RESPONSES: Record<
  AdmissionRefusal["code"],
  { status: number; code: string }
> = {
  busy: { status: 409, code: "CONVERSATION_BUSY" },
  owned: { status: 409, code: "CONVERSATION_OWNED" },
  queue_review: { status: 409, code: "QUEUE_REVIEW_REQUIRED" },
  debug_mode: { status: 409, code: "DEBUG_MODE_ACTIVE" },
  stopping: { status: 503, code: "SERVER_STOPPING" },
  not_enrolled: { status: 409, code: "CONVERSATION_NOT_ENROLLED" },
};

/** One answer per admission refusal, whichever entry was refused. */
function admissionRefusal(admission: AdmissionRefusal): PromptRefusal {
  const { status, code } = REFUSAL_RESPONSES[admission.code];
  return { status, body: { error: admission.message, code } };
}

/**
 * Why a conversation command (or `/collab`, a claim) cannot start now, or
 * null. A command runs through the command service rather than the core's
 * mailbox, so the route asks the core's admission before dispatching it.
 */
async function coreCommandHold(
  deps: Pick<CoreConversationPromptDeps, "admission">,
  conversation: ConversationState,
  turn: Extract<HoldTurn, "command" | "claim">,
): Promise<PromptRefusal | null> {
  const held = await deps.admission(conversation.id, turn);
  return held === null ? null : admissionRefusal(held);
}

/** The prompt request's own event stream: what the client reads while the turn runs. */
function eventStream() {
  const encoder = new TextEncoder();
  const sink: {
    controller: ReadableStreamDefaultController<Uint8Array> | null;
  } = { controller: null };
  const stream = new ReadableStream<Uint8Array>({
    start(controller) {
      sink.controller = controller;
    },
    cancel() {
      // The work belongs to the conversation, not to this request: it runs on.
    },
  });
  return {
    emit(event: string, data: unknown): void {
      try {
        sink.controller?.enqueue(
          encoder.encode(`event: ${event}\ndata: ${JSON.stringify(data)}\n\n`),
        );
      } catch {
        // The sender went away; the work is unaffected.
      }
    },
    close(): void {
      try {
        sink.controller?.close();
      } catch {
        // Already closed.
      }
    },
    response: () =>
      new Response(stream, {
        headers: {
          "Content-Type": "text/event-stream",
          "Cache-Control": "no-cache",
          Connection: "keep-alive",
        },
      }),
  };
}

/**
 * A message to a conversation the core runs, from whichever transport
 * carried it: one message into its mailbox, its events (content, error,
 * aborted) streamed to the caller's sink until it settles. A conversation
 * command runs through the command service instead. The caller ends its own
 * stream.
 */
export async function sendCorePrompt(
  deps: CoreConversationPromptDeps,
  input: CorePromptSend,
): Promise<CorePromptOutcome> {
  const { projectPath, target, conversation, message } = input;
  const managed = managedRefusal(conversation);
  if (managed !== null) return refused(managed);
  const text = message.text.trim();
  if (hasCollabPrefix(text)) return refused(collaborationRefusal(target));
  const feedback =
    message.documentFeedback !== undefined ||
    (message.notepadFeedback?.length ?? 0) > 0;
  if (text.length === 0 && (message.images?.length ?? 0) === 0 && !feedback)
    return refused({
      status: 400,
      body: { error: "Either prompt text, an image or feedback is required" },
    });

  // The backend is chosen with the first message and fixed from then on; the
  // turn itself adopts it, so this is only the early answer.
  const backend = message.backend ?? conversation.agentBackend;
  if (backend !== conversation.agentBackend && backendLocked(conversation))
    return refused(backendMismatch(conversation, backend));
  const { draft } = input;
  const clearDraft = async () => {
    if (draft === undefined) return;
    await deps
      .clearPendingPromptText(
        projectPath,
        conversationTargetStoreSessionName(target),
        conversation.id,
        draft,
      )
      .catch((error: unknown) =>
        deps.log.warn("conversation_core.pending_draft_clear_failed", {
          conversationId: conversation.id,
          error: getErrorMessage(error),
        }),
      );
  };

  const command = parseConversationCommand(text);
  if (command !== null) {
    const held =
      (await deps.commandRefusal(text, backend)) ??
      (await coreCommandHold(deps, conversation, "command"));
    if (held !== null) return refused(held);
    let modelSelection = message.modelSelection;
    if (modelSelection !== undefined) {
      const admitted = await deps.admitCommandModel({
        projectPath,
        backend,
        selection: modelSelection,
      });
      if (!admitted.ok) return refused(admitted.refusal);
      modelSelection = admitted.selection;
    }
    // The command service reads the backend from the row: a first input's choice is taken first.
    if (backend !== conversation.agentBackend) {
      await deps.adoptBackend(
        {
          projectPath,
          storeSessionName: conversationTargetStoreSessionName(target),
          conversationId: conversation.id,
        },
        backend,
      );
    }
    return runCommand(deps, input, command, text, modelSelection, clearDraft);
  }

  let endingReported = false;
  const emit = (event: string, data: unknown): void => {
    if (event === "error" || event === "aborted") endingReported = true;
    input.sink.emit(event, data);
  };
  const admission = await deps.sendUserMessage({
    conversationId: conversation.id,
    text,
    ...(message.images !== undefined && message.images.length > 0
      ? { images: message.images }
      : {}),
    ...(message.documentFeedback !== undefined
      ? { documentFeedback: message.documentFeedback }
      : {}),
    ...(message.notepadFeedback !== undefined &&
    message.notepadFeedback.length > 0
      ? { notepadFeedback: [...message.notepadFeedback] }
      : {}),
    ...(message.modelSelection !== undefined
      ? { modelSelection: message.modelSelection }
      : {}),
    ...(message.backend !== undefined ? { backend: message.backend } : {}),
    ...(message.autonomous === true ? { autonomous: true } : {}),
    // Review feedback is composed by CC from comments, not typed by the person.
    inputOrigin: message.inputOrigin ?? (feedback ? "generated" : "user"),
    stream: { emit },
  });
  if (admission.kind === "refused") {
    deps.log.warn("conversation_core.prompt_refused", {
      conversationId: conversation.id,
      code: admission.code,
    });
    return refused(admissionRefusal(admission));
  }
  deps.log.info("conversation_core.prompt_accepted", {
    conversationId: conversation.id,
    promptLength: text.length,
  });
  await clearDraft();

  const settled = admission.settled.then(
    (report): PromptSettlement => {
      if (report.status === "succeeded") return { error: null, aborted: false };
      const failure = report.failure ?? "The turn did not complete";
      if (!endingReported)
        emit(report.status === "failed" ? "error" : "aborted", {
          message: failure,
        });
      return { error: failure, aborted: report.status !== "failed" };
    },
    (error: unknown): PromptSettlement => {
      const failure = getErrorMessage(error);
      emit("error", { message: failure });
      return { error: failure, aborted: false };
    },
  );
  return { kind: "accepted", settled };
}

/**
 * A person's prompt to a conversation the core runs, over HTTP: the same
 * event stream the conversation actor's prompts use (content, error, aborted,
 * then done once the turn settles), or the refusal as JSON. The person's
 * draft is cleared once the message is accepted.
 */
export async function promptCoreConversation(
  deps: CoreConversationPromptDeps,
  input: CoreConversationPrompt,
): Promise<Response> {
  const { body } = input;
  const events = eventStream();
  const outcome = await sendCorePrompt(deps, {
    projectPath: input.projectPath,
    target: input.target,
    conversation: input.conversation,
    message: {
      text: body.prompt,
      ...(body.images !== undefined ? { images: body.images } : {}),
      ...(body.documentFeedback !== undefined
        ? { documentFeedback: body.documentFeedback }
        : {}),
      ...(body.notepadFeedback !== undefined
        ? { notepadFeedback: [body.notepadFeedback] }
        : {}),
      ...(body.modelSelection !== undefined
        ? { modelSelection: body.modelSelection }
        : {}),
      ...(body.backend !== undefined ? { backend: body.backend } : {}),
    },
    sink: events,
    draft: body.submittedPendingPromptText ?? body.prompt,
  });
  if (outcome.kind === "refused") {
    events.close();
    return asResponse(outcome.refusal);
  }
  void outcome.settled.then(() => {
    events.emit("done", {});
    events.close();
  });
  return events.response();
}

/**
 * A conversation command (/commit, /merge, …) runs to its outcome through the
 * command service, which records the command message itself; its agent work
 * reaches this conversation as task turns in its own turn order.
 */
function runCommand(
  deps: CoreConversationPromptDeps,
  input: CorePromptSend,
  command: ParsedConversationCommand,
  text: string,
  modelSelection: BackendModelSelection | undefined,
  clearDraft: () => Promise<void>,
): CorePromptOutcome {
  const { projectPath, target, conversation } = input;
  deps.log.info("conversation_core.command_dispatched", {
    conversationId: conversation.id,
    command: command.command,
  });
  const settled = (async (): Promise<PromptSettlement> => {
    try {
      const outcome = await deps.dispatchCommand({
        projectPath,
        projectName: target.projectName,
        // A project conversation has no session worktree, which the command service refuses
        // for the commands that need one; its notices still reach the project conversation.
        ...(target.scope === "session"
          ? { sessionName: target.sessionName }
          : {
              sessionName: null,
              noticeSessionName: conversationTargetStoreSessionName(target),
            }),
        conversationId: conversation.id,
        parsed: command,
        rawText: text,
        ...(modelSelection !== undefined ? { modelSelection } : {}),
      });
      await clearDraft();
      const fallback = ticketCommandFallbackMessage(outcome);
      if (fallback === null) return { error: null, aborted: false };
      input.sink.emit("error", { message: fallback });
      return { error: fallback, aborted: false };
    } catch (error) {
      const failure = getErrorMessage(error);
      input.sink.emit("error", { message: failure });
      return { error: failure, aborted: false };
    }
  })();
  return { kind: "accepted", settled };
}
